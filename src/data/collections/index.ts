/**
 * Get top favorite collection items based on the 4 official selection rules:
 * 1. Highest likes count
 * 2. Constructor diversity (max 1 shot per team)
 * 3. Verified provenance & date
 * 4. Strict limit cap (default: 6 items)
 */
export const getTopFavoriteCollectionItems = (limit = 6): CollectionItem[] => {
  const sorted = [...COLLECTION_ITEMS].sort((a, b) => (b.likes || 0) - (a.likes || 0));
  const selected: CollectionItem[] = [];
  const seenTeams = new Set<string>();

  for (const item of sorted) {
    if (!seenTeams.has(item.teamId)) {
      seenTeams.add(item.teamId);
      selected.push(item);
      if (selected.length >= limit) break;
    }
  }

  return selected;
};

/** Get all items for a specific team */
export const getTeamCollection = (teamId: string): CollectionItem[] =>
  COLLECTION_ITEMS.filter((item) => item.teamId === teamId);

/** Get items filtered by team + category */
export const getTeamCategoryCollection = (
  teamId: string,
  category: string,
): CollectionItem[] => {
  if (category === 'all') return getTeamCollection(teamId);
  return COLLECTION_ITEMS.filter(
    (item) => item.teamId === teamId && item.category === category,
  );
};
